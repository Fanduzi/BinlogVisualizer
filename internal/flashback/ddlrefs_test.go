func TestDDLReferencesReadsEveryName(t *testing.T) {
	cases := []struct {
		sql     string
		session string
		want    []ddlRef
	}{
		{"RENAME TABLE rn.t2 TO rn.tmp, rn.t1 TO rn.t2, rn.tmp TO rn.t1", "", []ddlRef{{"rn", "t2"}, {"rn", "tmp"}, {"rn", "t1"}, {"rn", "t2"}, {"rn", "tmp"}, {"rn", "t1"}}},
		{"RENAME TABLE other.x TO other.y, t2 TO t1", "rn", []ddlRef{{"other", "x"}, {"other", "y"}, {"rn", "t2"}, {"rn", "t1"}}},
		{"rename tables a.b to c.d;", "", []ddlRef{{"a", "b"}, {"c", "d"}}},
		{"DROP TABLE `rn`.`z`,`rn`.`t1` /* generated by server */", "", []ddlRef{{"rn", "z"}, {"rn", "t1"}}},
		{"DROP TEMPORARY TABLE IF EXISTS z, `we``ird` CASCADE", "s", []ddlRef{{"s", "z"}, {"s", "we`ird"}}},
		{"DROP VIEW IF EXISTS v1, s2.v2", "s", []ddlRef{{"s", "v1"}, {"s2", "v2"}}},
		{"TRUNCATE TABLE t1", "rn", []ddlRef{{"rn", "t1"}}},
		{"TRUNCATE rn.t1", "", []ddlRef{{"rn", "t1"}}},
		{"ALTER TABLE rn.t1 RENAME TO rn.t9", "", []ddlRef{{"rn", "t1"}, {"rn", "t9"}}},
		{"ALTER TABLE z ADD COLUMN c INT, RENAME AS other.t1", "rn", []ddlRef{{"rn", "z"}, {"other", "t1"}}},
		{"ALTER TABLE z RENAME COLUMN a TO b, RENAME INDEX i TO j", "rn", []ddlRef{{"rn", "z"}}},
		{"ALTER TABLE b ADD CONSTRAINT fk FOREIGN KEY (x) REFERENCES a (id) ON DELETE CASCADE", "qa", []ddlRef{{"qa", "b"}, {"qa", "a"}}},
		{"ALTER ONLINE IGNORE TABLE IF EXISTS qa.b ADD INDEX iv (v), ALGORITHM=INPLACE", "", []ddlRef{{"qa", "b"}}},
		{"ALTER TABLE qa.b COMMENT 'RENAME TO qa.a; SELECT'", "", []ddlRef{{"qa", "b"}}},
		{"CREATE TABLE IF NOT EXISTS n (id INT PRIMARY KEY, v VARCHAR(10) DEFAULT 'x')", "rn", []ddlRef{{"rn", "n"}}},
		{"CREATE TABLE n LIKE rn.t1", "", []ddlRef{{"", "n"}, {"rn", "t1"}}},
		{"CREATE OR REPLACE TEMPORARY TABLE n (LIKE t1)", "rn", []ddlRef{{"rn", "n"}, {"rn", "t1"}}},
		{"CREATE UNIQUE INDEX ix USING BTREE ON rn.t1 (v)", "", []ddlRef{{"rn", "t1"}}},
		{"DROP INDEX ix ON t1 ALGORITHM=INPLACE LOCK=NONE", "rn", []ddlRef{{"rn", "t1"}}},
		{"DROP DATABASE IF EXISTS shop", "", []ddlRef{{"shop", ""}}},
		{"CREATE SCHEMA IF NOT EXISTS shop DEFAULT CHARACTER SET utf8mb4", "", []ddlRef{{"shop", ""}}},
		{"ALTER DATABASE CHARACTER SET utf8mb4", "rn", []ddlRef{{"rn", ""}}},
		{"-- note\nDROP TABLE # trailing\n t1", "rn", []ddlRef{{"rn", "t1"}}},
		{"GRANT SELECT ON rn.t1 TO 'u'@'%'", "", nil},
		{"CREATE USER 'u'@'%' IDENTIFIED BY 'x'", "", nil},
		{"DROP USER u", "", nil},
		{"SET PASSWORD FOR u = 'x'", "", nil},
	}
	for _, tc := range cases {
		got, ok := ddlReferences(tc.sql, tc.session, "", mysqlexpr.Dialect{})
		if !ok || !reflect.DeepEqual(got, tc.want) {
			t.Errorf("%s: got %v ok=%v, want %v", tc.sql, got, ok, tc.want)
		}
	}
}

// Every statement shape this reader does not know completely refuses.
func TestDDLReferencesFailsClosed(t *testing.T) {
	for _, sql := range []string{
		"",
		"RENAME TABLE a TO",
		"RENAME TABLE a TO b c",
		"RENAME TABLE IF EXISTS a TO b",
		"RENAME TABLE a WAIT 1 TO b",
		"DROP TABLE a, ",
		"DROP TABLE a /*!50001 , t1 */",
		"DROP TABLE a /*M!100100 , t1 */",
		"DROP TABLE \"t1\"",
		"DROP TABLE `t1",
		"DROP TABLE a /* open",
		"DROP TABLE a; DROP TABLE t1",
		"ALTER TABLE z EXCHANGE PARTITION p WITH TABLE t1",
		"ALTER TABLE z RENAME",
		"ALTER VIEW v AS SELECT * FROM t1",
		"ALTER EVENT e RENAME TO e2",
		"CREATE TABLE n AS SELECT * FROM t1",
		"CREATE TABLE n SELECT 1",
		"CREATE TABLE n TABLE t1",
		"CREATE TABLE n (c INT) WITH SYSTEM VERSIONING",
		"CREATE TABLE n (c INT CHECK (c LIKE 'a%'))",
		"CREATE VIEW v AS SELECT 1",
		"CREATE DEFINER=root@localhost TRIGGER tr BEFORE INSERT ON t1 FOR EACH ROW SET NEW.v = 1",
		"CREATE PROCEDURE p() BEGIN END",
		"DROP TRIGGER tr",
		"DROP PROCEDURE p",
		"TRUNCATE TABLE t1 WAIT 1",
		"CREATE TABLESPACE ts ADD DATAFILE 'x'",
		"SET GLOBAL x = 1",
		"OPTIMIZE TABLE t1",
	} {
		if got, ok := ddlReferences(sql, "rn", "", mysqlexpr.Dialect{}); ok {
			t.Errorf("%q read as %v; want refusal", sql, got)
		}
	}
}

type fakeSelection struct{ table, schema string }

func (s fakeSelection) MayHoldTable(schema, table string) bool {
	return table == s.table && (schema == "" || schema == s.schema)
}
func (s fakeSelection) MayHoldSchema(schema string) bool { return schema == "" || schema == s.schema }

func TestDDLRefusalUnderSelection(t *testing.T) {
	sel := fakeSelection{schema: "rn", table: "t1"}
	cases := []struct {
		name      string
		ev        model.NormalizedEvent
		refuse    bool
		table     string
		unreadMsg bool
	}{
		{"later pair", model.NormalizedEvent{EventType: "DDL", Schema: "rn", Table: "t2", QuerySchema: "rn", QuerySQL: "RENAME TABLE t2 TO tmp, t1 TO t2"}, true, "rn.t1", false},
		{"session schema after qualified name", model.NormalizedEvent{EventType: "DDL", Schema: "other", Table: "x", QuerySchema: "rn", QuerySQL: "RENAME TABLE other.x TO other.y, t2 TO t1"}, true, "rn.t1", false},
		{"unknown session matches any schema", model.NormalizedEvent{EventType: "DDL", QuerySQL: "DROP TABLE z, t1"}, true, "z, t1", false},
		{"whole schema", model.NormalizedEvent{EventType: "DDL", QuerySQL: "DROP DATABASE rn"}, true, "", false},
		{"other table", model.NormalizedEvent{EventType: "DDL", Schema: "rn", Table: "t2", QuerySchema: "rn", QuerySQL: "ALTER TABLE t2 ADD INDEX i (v)"}, false, "", false},
		{"other schema", model.NormalizedEvent{EventType: "DDL", QuerySQL: "DROP DATABASE shop"}, false, "", false},
		{"account statement", model.NormalizedEvent{EventType: "DDL", QuerySQL: "GRANT SELECT ON rn.t1 TO u"}, false, "", false},
		{"unread shape", model.NormalizedEvent{EventType: "DDL", Schema: "rn", Table: "v", QuerySchema: "rn", QuerySQL: "CREATE VIEW v AS SELECT * FROM t2"}, true, "", true},
		{"executable comment", model.NormalizedEvent{EventType: "DDL", Schema: "rn", Table: "z", QuerySchema: "rn", QuerySQL: "DROP TABLE z /*!99999 , t1 */"}, true, "", true},
		{"truncated text", model.NormalizedEvent{EventType: "DDL", Schema: "rn", Table: "z", QuerySchema: "rn", QuerySQL: "DROP TABLE z", QueryTruncated: true}, true, "", true},
	}
	for _, tc := range cases {
		p := New(Options{Selection: sel})
		p.Note(tc.ev)
		reason, table, ok := RefusalDetails(p.flashErr)
		if !tc.refuse {
			if p.flashErr != nil {
				t.Errorf("%s: refused: %v", tc.name, p.flashErr)
			}
			continue
		}
		if !ok || reason != "ddl_in_range" || table != tc.table {
			t.Errorf("%s: reason %q table %q err %v", tc.name, reason, table, p.flashErr)
			continue
		}
		if unread := strings.Contains(p.flashErr.Error(), "could not be read completely"); unread != tc.unreadMsg {
			t.Errorf("%s: message %v", tc.name, p.flashErr)
		}
	}
}
