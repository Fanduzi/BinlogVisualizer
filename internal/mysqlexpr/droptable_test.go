func TestParseDropTableLists(t *testing.T) {
	cases := []struct {
		sql  string
		want []QualifiedIdent
	}{
		{"DROP TABLE `q341_dr`.`z`,`q341_dr`.`t1` /* generated by server */", []QualifiedIdent{{"q341_dr", "z"}, {"q341_dr", "t1"}}},
		{"DROP TABLE `q368_a`.`x`,`q368_b`.`t1` /* generated by server */", []QualifiedIdent{{"q368_a", "x"}, {"q368_b", "t1"}}},
		{"drop table `x`, `q368_b`.`t1`", []QualifiedIdent{{"", "x"}, {"q368_b", "t1"}}},
		{"DROP TEMPORARY TABLE IF EXISTS z, `we``ird` CASCADE", []QualifiedIdent{{"", "z"}, {"", "we`ird"}}},
		{"DROP TABLES `a,b`.`c`, `a.b`.`d`", []QualifiedIdent{{"a,b", "c"}, {"a.b", "d"}}},
		{"DROP TABLE `sch`.`a``b`", []QualifiedIdent{{"sch", "a`b"}}},
		{"DROP TABLE q341_dr.z, q341_dr.t1", []QualifiedIdent{{"q341_dr", "z"}, {"q341_dr", "t1"}}},
		{"DROP\nTABLE\n`q368_a`.`x`,\n`q368_b`.`t1`", []QualifiedIdent{{"q368_a", "x"}, {"q368_b", "t1"}}},
		{"-- note\nDROP TABLE # trailing\n t1", []QualifiedIdent{{"", "t1"}}},
		{"DROP TABLE t1 RESTRICT;", []QualifiedIdent{{"", "t1"}}},
		{"  DROP   TEMPORARY   TABLE   IF   EXISTS   `db` . `t`  ", []QualifiedIdent{{"db", "t"}}},
	}
	for _, tc := range cases {
		got, isDrop, ok := ParseDropTable(tc.sql, Dialect{})
		if !isDrop || !ok || !reflect.DeepEqual(got, tc.want) {
			t.Errorf("%s:\n got %#v isDrop=%v ok=%v\nwant %#v", tc.sql, got, isDrop, ok, tc.want)
		}
	}
}

func TestParseDropTableRejectsUnreadable(t *testing.T) {
	for _, sql := range []string{
		"DROP TABLE a, ",
		"DROP TABLE a /*!50001 , t1 */",
		"DROP TABLE a /*M!100100 , t1 */",
		"DROP TABLE \"t1\"",
		"DROP TABLE `t1",
		"DROP TABLE a /* open",
		"DROP TABLE t /*!",
		"DROP TABLE a; DROP TABLE t1",
		"DROP TABLE IF t1",
	} {
		names, isDrop, ok := ParseDropTable(sql, Dialect{})
		if !isDrop || ok || names != nil {
			t.Errorf("%q: names=%v isDrop=%v ok=%v, want unreadable DROP TABLE", sql, names, isDrop, ok)
		}
	}
}

// A quoted keyword is a name. Dropping the quoted flag reads `if` as IF EXISTS.
func TestParseDropTableQuotedIfIsAName(t *testing.T) {
	got, isDrop, ok := ParseDropTable("DROP TABLE `if`,`t2` /* generated by server */", Dialect{})
	want := []QualifiedIdent{{Table: "if"}, {Table: "t2"}}
	if !isDrop || !ok || !reflect.DeepEqual(got, want) {
		t.Fatalf("got %#v isDrop=%v ok=%v, want the two quoted names", got, isDrop, ok)
	}
}

func TestParseDropTableVersionCommentAndANSIQuotes(t *testing.T) {
	d := Dialect{VersionID: MySQLVersionID("8.0.36"), ANSIQuotes: true}
	got, isDrop, ok := ParseDropTable("DROP /*!40005 TEMPORARY */ TABLE IF EXISTS `td 2``x`,`td1`", d)
	want := []QualifiedIdent{{Table: "td 2`x"}, {Table: "td1"}}
	if !isDrop || !ok || !reflect.DeepEqual(got, want) {
		t.Fatalf("versioned temporary: %#v isDrop=%v ok=%v", got, isDrop, ok)
	}
	got, isDrop, ok = ParseDropTable(`DROP TABLE IF EXISTS "t9","nope2"`, d)
	want = []QualifiedIdent{{Table: "t9"}, {Table: "nope2"}}
	if !isDrop || !ok || !reflect.DeepEqual(got, want) {
		t.Fatalf("ansi quotes: %#v isDrop=%v ok=%v", got, isDrop, ok)
	}
	got, isDrop, ok = ParseDropTable(`DROP TABLE "we""ird"`, d)
	if !isDrop || !ok || len(got) != 1 || got[0].Table != `we"ird` {
		t.Fatalf("doubled quote: %#v ok=%v", got, ok)
	}
	// A comment the server version does not run is not a name. One it might
	// run, with no version to compare, stays unreadable.
	got, isDrop, ok = ParseDropTable("DROP TABLE z /*!99999 , t1 */", Dialect{VersionID: 80036})
	if !isDrop || !ok || len(got) != 1 || got[0].Table != "z" {
		t.Fatalf("future comment: %#v ok=%v", got, ok)
	}
	got, isDrop, ok = ParseDropTable("DROP TABLE a /*!50001 , t2 */", Dialect{VersionID: 80036})
	want = []QualifiedIdent{{Table: "a"}, {Table: "t2"}}
	if !isDrop || !ok || !reflect.DeepEqual(got, want) {
		t.Fatalf("executed comment: %#v ok=%v", got, ok)
	}
	// The server's own version runs the comment. One version newer does not.
	// MySQL skips a MariaDB /*M! */ comment.
	got, isDrop, ok = ParseDropTable("DROP TABLE a /*!80036 , t2 */", Dialect{VersionID: 80036})
	if !isDrop || !ok || !reflect.DeepEqual(got, want) {
		t.Fatalf("same version: %#v ok=%v", got, ok)
	}
	got, isDrop, ok = ParseDropTable("DROP TABLE z /*!80037 , t1 */", Dialect{VersionID: 80036})
	if !isDrop || !ok || len(got) != 1 || got[0].Table != "z" {
		t.Fatalf("next version: %#v ok=%v", got, ok)
	}
	got, isDrop, ok = ParseDropTable("DROP TABLE a /*M!100100 , t1 */", Dialect{VersionID: 80036})
	if !isDrop || !ok || len(got) != 1 || got[0].Table != "a" {
		t.Fatalf("mysql skips maria comment: %#v ok=%v", got, ok)
	}
	// 50001 would run if /*M! were treated as a MySQL version comment.
	got, isDrop, ok = ParseDropTable("DROP TABLE a /*M!50001 , t2 */", Dialect{VersionID: 80036})
	if !isDrop || !ok || len(got) != 1 || got[0].Table != "a" {
		t.Fatalf("mysql runs maria comment: %#v ok=%v", got, ok)
	}
}

func TestVersionCommentDigitWidth(t *testing.T) {
	mysql80 := Dialect{VersionID: 80036}
	mysql84 := Dialect{VersionID: 80411}
	maria := Dialect{VersionID: 110809, MariaDB: true}
	cases := []struct {
		name string
		d    Dialect
		sql  string
		want []string
		bad  bool
	}{
		// 6th digit stays in the body on MySQL when no space follows it.
		{"mysql80 seven digits", mysql80, "DROP TABLE z, /*!800369_t, t_keep */", []string{"z", "9_t", "t_keep"}, false},
		{"mysql84 seven-ish", mysql84, "DROP TABLE z, /*!800369_t, t_keep */", []string{"z", "9_t", "t_keep"}, false},
		{"mysql80 seven digit form", mysql80, "DROP TABLE z, /*!1000009_t, t_keep */", []string{"z", "09_t", "t_keep"}, false},
		{"mysql84 seven digit form", mysql84, "DROP TABLE z, /*!1000009_t, t_keep */", []string{"z", "09_t", "t_keep"}, false},
		// From 8.1, six digits count only when whitespace follows them.
		{"mysql84 six digits and space", mysql84, "DROP TABLE z /*!080411 , t2 */", []string{"z", "t2"}, false},
		{"mysql84 six digits too new", mysql84, "DROP TABLE z /*!080412 , t2 */", []string{"z"}, false},
		{"mysql80 six digits are five", mysql80, "DROP TABLE z /*!080411 , t2 */", nil, true},
		// MariaDB takes six whenever the sixth character is a digit.
		{"maria six from seven", maria, "DROP TABLE z, /*!1100009_t, t_keep */", []string{"z", "9_t", "t_keep"}, false},
		{"maria M! six from seven", maria, "DROP TABLE z, /*M!1100009_t, t_keep */", []string{"z", "9_t", "t_keep"}, false},
		{"maria six too new", maria, "DROP TABLE z /*!1108109_t, t_keep */", []string{"z"}, false},
		{"maria six digit comment", maria, "DROP TABLE z /*!110809 , t2 */", []string{"z", "t2"}, false},
	}
	for _, tc := range cases {
		got, isDrop, ok := ParseDropTable(tc.sql, tc.d)
		if tc.bad {
			if !isDrop || ok {
				t.Errorf("%s: ok=%v got %#v, want unreadable", tc.name, ok, got)
			}
			continue
		}
		var names []string
		for _, n := range got {
			names = append(names, n.Table)
		}
		if !isDrop || !ok || !reflect.DeepEqual(names, tc.want) {
			t.Errorf("%s: got %v ok=%v, want %v", tc.name, names, ok, tc.want)
		}
	}
}

func TestRewrittenMariaDBDropIgnoresPreservedComment(t *testing.T) {
	sql := "DROP TABLE /*!110809 qa412.v_nover, qa412.not_dropped, */ `v_nover`,`v_above_eq` /* generated by server */"
	got, isDrop, ok := ParseDropTable(sql, Dialect{VersionID: 110809, MariaDB: true})
	want := []QualifiedIdent{{Table: "v_nover"}, {Table: "v_above_eq"}}
	if !isDrop || !ok || !reflect.DeepEqual(got, want) {
		t.Fatalf("got %#v ok=%v, want the rewritten names once", got, ok)
	}
}

func TestWithSessionDoesNotFillAfterQualifiedName(t *testing.T) {
	names, isDrop, ok := ParseDropTable("DROP TABLE db1.a, b", Dialect{})
	if !isDrop || !ok {
		t.Fatalf("parse: %#v ok=%v", names, ok)
	}
	got := WithSession(names, "", "eventdb")
	want := []QualifiedIdent{{Schema: "db1", Table: "a"}, {Table: "b"}}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %#v, want unqualified b left unqualified", got)
	}
}

func TestParseDropTableIgnoresOtherStatements(t *testing.T) {
	for _, sql := range []string{
		"DROP DATABASE shop",
		"DROP VIEW v",
		"DROP INDEX i ON t",
		"CREATE TABLE t (id INT)",
		"RENAME TABLE a TO b",
	} {
		if _, isDrop, ok := ParseDropTable(sql, Dialect{}); isDrop || ok {
			t.Errorf("%q recognized as DROP TABLE (ok=%v)", sql, ok)
		}
	}
}
