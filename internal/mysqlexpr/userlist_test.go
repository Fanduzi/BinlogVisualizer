package mysqlexpr

import (
	"reflect"
	"testing"
)

func TestParseDropUserLists(t *testing.T) {
	cases := []struct {
		sql  string
		want []string
	}{
		{"DROP USER 'a'@'h'", []string{"'a'@'h'"}},
		{"DROP USER 'a'@'h', 'b'@'%'", []string{"'a'@'h'", "'b'@'%'"}},
		{"DROP USER IF EXISTS 'a'@'h','b'@'h'", []string{"'a'@'h'", "'b'@'h'"}},
		{"drop user a@h, b", []string{"a@h", "b"}},
		{"DROP USER 'we''ird'@'h', 'n,o'@'h'", []string{"'we''ird'@'h'", "'n,o'@'h'"}},
		{"  DROP   USER   `svc`@`%` ;", []string{"`svc`@`%`"}},
		{"DROP USER 'a'@'h' /* generated by server */", []string{"'a'@'h'"}},
	}
	for _, tc := range cases {
		got, isDrop, ok := ParseDropUser(tc.sql, Dialect{})
		if !isDrop || !ok || !reflect.DeepEqual(got, tc.want) {
			t.Errorf("%s:\n got %#v isDrop=%v ok=%v\nwant %#v", tc.sql, got, isDrop, ok, tc.want)
		}
	}
}

func TestParseDropUserRejectsUnreadable(t *testing.T) {
	for _, sql := range []string{
		"DROP USER",
		"DROP USER 'a'@'h', ",
		"DROP USER 'a@'h'",
		"DROP USER 'a'@'h' PURGE",
		"DROP USER 'a'@'h'; DROP USER 'b'@'h'",
		"DROP USER 'a",
		"DROP USER IF 'a'@'h'",
	} {
		accounts, isDrop, ok := ParseDropUser(sql, Dialect{})
		if !isDrop || ok || accounts != nil {
			t.Errorf("%q: accounts=%v isDrop=%v ok=%v, want unreadable DROP USER", sql, accounts, isDrop, ok)
		}
	}
}

func TestParseDropUserIgnoresOtherStatements(t *testing.T) {
	for _, sql := range []string{
		"DROP TABLE t",
		"DROP ROLE 'r'@'h'",
		"CREATE USER 'a'@'h'",
		"RENAME USER 'a'@'h' TO 'b'@'h'",
	} {
		if _, isDrop, ok := ParseDropUser(sql, Dialect{}); isDrop || ok {
			t.Errorf("%q recognized as DROP USER (ok=%v)", sql, ok)
		}
	}
}

func TestParseRenameUserLists(t *testing.T) {
	cases := []struct {
		sql  string
		want []string
	}{
		{"RENAME USER 'a'@'h' TO 'b'@'h'", []string{"'a'@'h' TO 'b'@'h'"}},
		{"RENAME USER 'a'@'h' TO 'b'@'h', 'c'@'%' TO 'd'@'%'", []string{"'a'@'h' TO 'b'@'h'", "'c'@'%' TO 'd'@'%'"}},
		{"rename user a@h to b@h", []string{"a@h TO b@h"}},
		{"RENAME USER 'a'@'h' TO 'b'@'h';", []string{"'a'@'h' TO 'b'@'h'"}},
	}
	for _, tc := range cases {
		got, isRename, ok := ParseRenameUser(tc.sql, Dialect{})
		if !isRename || !ok || !reflect.DeepEqual(got, tc.want) {
			t.Errorf("%s:\n got %#v isRename=%v ok=%v\nwant %#v", tc.sql, got, isRename, ok, tc.want)
		}
	}
}

func TestParseRenameUserRejectsUnreadable(t *testing.T) {
	for _, sql := range []string{
		"RENAME USER 'a'@'h'",
		"RENAME USER 'a'@'h' TO",
		"RENAME USER 'a'@'h' 'b'@'h'",
		"RENAME USER 'a'@'h' TO 'b'@'h',",
		"RENAME USER 'a'@'h' TO 'b'@'h'; RENAME USER 'c'@'h' TO 'd'@'h'",
	} {
		targets, isRename, ok := ParseRenameUser(sql, Dialect{})
		if !isRename || ok || targets != nil {
			t.Errorf("%q: targets=%v isRename=%v ok=%v, want unreadable RENAME USER", sql, targets, isRename, ok)
		}
	}
}

func TestParseRenameUserIgnoresOtherStatements(t *testing.T) {
	for _, sql := range []string{
		"RENAME TABLE a TO b",
		"DROP USER 'a'@'h'",
		"ALTER USER 'a'@'h' IDENTIFIED BY 'x'",
	} {
		if _, isRename, ok := ParseRenameUser(sql, Dialect{}); isRename || ok {
			t.Errorf("%q recognized as RENAME USER (ok=%v)", sql, ok)
		}
	}
}
