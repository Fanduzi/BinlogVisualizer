// Package codehealth measures the code-health numbers that CI ratchets:
// oversized files, overly complex functions, issue references in comments
// and unreachable functions. The checked-in baseline.json holds the ceiling
// for each number. A change may lower a ceiling but never raise one, so
// existing debt does not block work while new debt fails the build.
package codehealth

import (
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// Limits are the caps the ratchet enforces. They live in the baseline so a
// change that loosens them shows up in review and fails CompareBaselines.
type Limits struct {
	FileLines       int `json:"file_lines"`
	GrowthTolerance int `json:"growth_tolerance_lines"`
	Complexity      int `json:"complexity"`
}

// DefaultLimits are the caps in docs/development/coding-standards.md.
var DefaultLimits = Limits{FileLines: 800, GrowthTolerance: 20, Complexity: 40}

// Measurement is what Measure finds in one tree. Deadcode is -1 until
// CountDeadcode fills it in, because it needs the deadcode tool.
type Measurement struct {
	// OversizedFiles maps a slash path to its line count, for non-test,
	// non-generated Go files over Limits.FileLines.
	OversizedFiles map[string]int
	// ComplexFunctions maps "pkgdir:Recv.Func" to its cyclomatic complexity,
	// for functions over Limits.Complexity.
	ComplexFunctions map[string]int
	// IssueRefs lists each issue or section reference found in a comment,
	// as "path:line: text".
	IssueRefs []string
	Deadcode  int
}

// issueRef matches an issue number (a hash followed by digits) or a section
// mark (the section sign followed by digits) in a comment. HTML entities such
// as "&#" plus digits and words such as "C#" are not matches; the fixture in
// testdata/refs pins both cases.
var issueRef = regexp.MustCompile(`(?:^|[^\w&#])#[0-9]+\b|§\s*[0-9]+`)

// Measure walks root and measures every Go file outside testdata, vendor,
// node_modules and hidden directories. Test files count for issue references
// only; generated files are skipped entirely.
func Measure(root string, lim Limits) (Measurement, error) {
	m := Measurement{OversizedFiles: map[string]int{}, ComplexFunctions: map[string]int{}, Deadcode: -1}
	fset := token.NewFileSet()
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if path != root && skipDir(d.Name()) {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") {
			return nil
		}
		src, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		f, err := parser.ParseFile(fset, path, src, parser.ParseComments)
		if err != nil {
			return err
		}
		if generated(f) {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		m.IssueRefs = append(m.IssueRefs, issueRefs(fset, f, rel)...)
		if strings.HasSuffix(path, "_test.go") {
			return nil
		}
		if n := countLines(src); n > lim.FileLines {
			m.OversizedFiles[rel] = n
		}
		pkgDir := filepath.ToSlash(filepath.Dir(rel))
		for name, c := range complexities(f) {
			key := pkgDir + ":" + name
			if c > lim.Complexity && c > m.ComplexFunctions[key] {
				m.ComplexFunctions[key] = c
			}
		}
		return nil
	})
	sort.Strings(m.IssueRefs)
	return m, err
}

// generated reports a file whose comments before the package clause say it
// is generated. That is ast.IsGenerated plus headers that tools such as swag
// write as "// Package x Code generated by ... DO NOT EDIT".
func generated(f *ast.File) bool {
	if ast.IsGenerated(f) {
		return true
	}
	for _, group := range f.Comments {
		if group.Pos() > f.Package {
			break
		}
		text := group.Text()
		if strings.Contains(text, "Code generated") && strings.Contains(text, "DO NOT EDIT") {
			return true
		}
	}
	return false
}

func skipDir(name string) bool {
	switch name {
	case "testdata", "vendor", "node_modules":
		return true
	}
	return strings.HasPrefix(name, ".")
}

func countLines(src []byte) int {
	n := strings.Count(string(src), "\n")
	if len(src) > 0 && src[len(src)-1] != '\n' {
		n++
	}
	return n
}

func issueRefs(fset *token.FileSet, f *ast.File, rel string) []string {
	var out []string
	for _, group := range f.Comments {
		for _, c := range group.List {
			lines := strings.Split(c.Text, "\n")
			start := fset.Position(c.Pos()).Line
			for i, line := range lines {
				for _, hit := range issueRef.FindAllString(line, -1) {
					out = append(out, rel+":"+strconv.Itoa(start+i)+": "+strings.TrimSpace(hit))
				}
			}
		}
	}
	return out
}
