// gateCase runs one pull request through what CI runs: the author's
// make codehealth-baseline (Update, unless handEdit replaces it), then
// check (Check) and the baseline comparison against the base tree
// (Compare with paydown, as on a pull request).
type gateCase struct {
	name     string
	base, pr tree
	baseGen  map[string]string
	baseDead map[string]string
	prDead   map[string]string
	// handEdit, when set, replaces Update: the author edits a copy of the
	// base baseline by hand.
	handEdit func(*Baseline)
	want     string
}

func (c gateCase) run(t *testing.T) []string {
	t.Helper()
	baseM := measure(t, c.base, c.baseGen)
	baseM.Deadcode = c.baseDead
	prev := Initial(DefaultLimits, c.baseGen, baseM)
	if c.baseDead == nil {
		prev.Deadcode = Ledger{}
	}
	next := clone(t, prev)
	var problems []string
	if c.handEdit != nil {
		c.handEdit(&next)
	} else {
		prM := measure(t, c.pr, prev.Generated)
		prM.Deadcode = c.prDead
		next, problems = Update(prev, prM)
	}
	prM := measure(t, c.pr, next.Generated)
	prM.Deadcode = c.prDead
	problems = append(problems, Check(next, prM)...)
	return append(problems, Compare(prev, baseM, next, prM, true)...)
}

// The base tree: mysql_runner.go is 3592 lines (3400 of them content and a
// complexity-60 Run), verifier.go 837.
var (
	runnerBody = complexFunc("Run", 60)
	runner     = file(3592, runnerBody+lines("r", 0, 3400))
	verifier   = file(837, lines("v", 0, 830))
	baseTree   = tree{"internal/r/mysql_runner.go": runner, "internal/t/verifier.go": verifier, "internal/t/small.go": file(10, "")}
	swag       = map[string]string{"internal/api/docs.go": "swag init"}
)

func runnerSplit(pieces ...string) tree {
	changes := tree{"internal/r/mysql_runner.go": ""}
	for i := 0; i < len(pieces); i += 2 {
		changes["internal/r/"+pieces[i]] = pieces[i+1]
	}
	return baseTree.with(changes)
}

