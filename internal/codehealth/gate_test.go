package codehealth

import (
	"strings"
	"testing"
)

// gateCase runs one pull request through what CI runs: the author's
// make codehealth-baseline (Update, unless handEdit replaces it), then
// check (Check) and the baseline comparison (Compare) against the base.
type gateCase struct {
	name     string
	base, pr tree
	baseGen  map[string]string
	baseDead map[string]string
	prDead   map[string]string
	from     map[string]string
	// handEdit, when set, replaces Update: the author edits a copy of the
	// base baseline by hand.
	handEdit func(*Baseline)
	want     string
}

func (c gateCase) run(t *testing.T) []string {
	t.Helper()
	baseM := measure(t, c.base, c.baseGen)
	baseM.Deadcode = c.baseDead
	prev := Initial(DefaultLimits, c.baseGen, baseM)
	if c.baseDead == nil {
		prev.Deadcode = Ledger{}
	}
	next := clone(t, prev)
	var problems []string
	if c.handEdit != nil {
		c.handEdit(&next)
	} else {
		prM := measure(t, c.pr, prev.Generated)
		prM.Deadcode = c.prDead
		updated, refused := Update(prev, prM, c.from)
		next, problems = updated, refused
	}
	prM := measure(t, c.pr, next.Generated)
	prM.Deadcode = c.prDead
	problems = append(problems, Check(next, prM)...)
	existed := func(path string) bool { _, ok := c.base[path]; return ok }
	return append(problems, Compare(prev, next, prM, existed)...)
}

const genHeader = "// Code generated by hand. DO NOT EDIT.\n"

var (
	runner   = file(3592, complexFunc("Run", 60))
	verifier = file(837, "")
	baseTree = tree{"internal/r/mysql_runner.go": runner, "internal/t/verifier.go": verifier, "internal/t/small.go": file(10, "")}
)

// Every row is a way QA found or could find to get debt past the gate,
// and must fail; the rows at the end are legitimate changes that must pass.
func TestGateBypasses(t *testing.T) {
	cases := []gateCase{
		{name: "new 900-line file with a generated header", pr: tree{"x/g.go": genHeader + file(900, "")}, want: "files: new file over 800 lines: x/g.go"},
		{name: "new complexity-50 function with a generated header", pr: tree{"x/g.go": genHeader + file(200, complexFunc("F", 50))}, want: "complex_functions: new function over 40 complexity: x:F"},
		{
			name: "generated header on an existing file, then the file grows",
			base: baseTree, pr: baseTree.with(tree{"internal/r/mysql_runner.go": genHeader + runner + strings.Repeat("\n", 40)}),
			want: "files: internal/r/mysql_runner.go grew to 3633 lines",
		},
		{
			name: "generated header on an existing file, and the file added to generated_files",
			base: baseTree, pr: baseTree.with(tree{"internal/r/mysql_runner.go": genHeader + runner}),
			handEdit: func(b *Baseline) {
				b.Generated["internal/r/mysql_runner.go"] = "hand"
				delete(b.Files, "internal/r/mysql_runner.go")
				delete(b.ComplexFunctions, "internal/r:Run")
			},
			want: "generated_files: adds internal/r/mysql_runner.go, which existed before this change",
		},
		{
			name: "new file added to generated_files with the header after a blank line",
			pr:   tree{"x/g.go": "\n" + genHeader + file(900, "")},
			handEdit: func(b *Baseline) {
				b.Generated["x/g.go"] = "hand"
			},
			want: "generated_files: adds x/g.go, whose first line is not the hand header",
		},
		{
			name: "new file added to generated_files with the marker in a doc comment",
			pr:   tree{"x/g.go": "// Package x Code generated by hand. DO NOT EDIT.\n" + file(900, "")},
			handEdit: func(b *Baseline) {
				b.Generated["x/g.go"] = "hand"
			},
			want: "files: new file over 800 lines: x/g.go",
		},
		{
			name: "slot swap: shrink verifier.go under the cap, drop it, add a new 837-line file under its key",
			base: baseTree, pr: baseTree.with(tree{"internal/t/verifier.go": file(799, ""), "internal/t/new.go": file(837, "")}),
			handEdit: func(b *Baseline) {
				delete(b.Files, "internal/t/verifier.go")
				b.Files["internal/t/new.go"] = Entry{Value: 837}
			},
			want: "files: adds internal/t/new.go (837); a new file over the limit fails",
		},
		{
			name: "slot swap dressed as a split",
			base: baseTree, pr: baseTree.with(tree{"internal/t/verifier.go": file(799, ""), "internal/t/new.go": file(837, "")}),
			from: map[string]string{"internal/t/new.go": "internal/t/verifier.go"},
			want: "files: internal/t/verifier.go split into [internal/t/new.go] has 1636 lines in total",
		},
		{
			name: "split_from an entry that is no longer in the baseline",
			base: baseTree.with(tree{"internal/t/verifier.go": file(700, "")}), pr: baseTree.with(tree{"internal/t/new.go": file(837, "")}),
			from: map[string]string{"internal/t/new.go": "internal/t/verifier.go"},
			want: "split_from internal/t/verifier.go, which is not in the previous baseline",
		},
		{
			name: "move debt between entries: rename a key and grow it, paid for by another ceiling",
			base: baseTree, pr: baseTree.with(tree{"internal/t/verifier.go": "", "internal/t/verifier2.go": file(1037, ""), "internal/r/mysql_runner.go": file(3392, complexFunc("Run", 60))}),
			handEdit: func(b *Baseline) {
				delete(b.Files, "internal/t/verifier.go")
				b.Files["internal/t/verifier2.go"] = Entry{Value: 1037, SplitFrom: "internal/t/verifier.go"}
				b.Files["internal/r/mysql_runner.go"] = Entry{Value: 3392}
			},
			want: "files: internal/t/verifier.go split into [internal/t/verifier2.go] has 1037 lines in total",
		},
		{
			name: "re-spent headroom: shrink a file by 300 lines without lowering the ceiling",
			base: baseTree, pr: baseTree.with(tree{"internal/r/mysql_runner.go": file(3292, complexFunc("Run", 60))}),
			handEdit: func(*Baseline) {},
			want:     "files: internal/r/mysql_runner.go is down to 3292 lines, ceiling 3592; run make codehealth-baseline",
		},
		{
			name: "re-spent headroom: after lowering, grow back",
			base: baseTree.with(tree{"internal/r/mysql_runner.go": file(3292, complexFunc("Run", 60))}), pr: baseTree,
			want: "files: internal/r/mysql_runner.go grew to 3592 lines, ceiling 3292",
		},
		{
			name: "re-spent headroom: drop refs in one file, add them in another",
			base: tree{"a.go": "package p\n// #1 #2 #3\n", "b.go": "package p\n// #4\n"},
			pr:   tree{"a.go": "package p\n", "b.go": "package p\n// #4 #5 #6 #7\n"},
			want: "issue_refs: b.go grew to 4 issue references",
		},
		{
			name: "re-spent headroom: drop refs without lowering the ceiling",
			base: tree{"a.go": "package p\n// #1 #2 #3\n"}, pr: tree{"a.go": "package p\n// #1\n"},
			handEdit: func(*Baseline) {}, want: "issue_refs: a.go is down to 1",
		},
		{
			name: "ref rewording keeps the count: #12 becomes issue 12, GH-12, PR#12, a URL",
			base: tree{"a.go": "package p\n// #12 #13 #14 #15\n"},
			pr:   tree{"a.go": "package p\n// issue 12, GH-13, PR#14, https://github.com/o/r/issues/15\n", "b.go": "package p\n// ＃1\n"},
			want: "issue_refs: b.go has 1 issue references in comments",
		},
		{
			name: "re-spent headroom: delete one dead function, add another",
			base: tree{"a.go": "package p\n"}, pr: tree{"a.go": "package p\n"},
			baseDead: map[string]string{"x:Old": "x/a.go:1:6"}, prDead: map[string]string{"x:New": "x/a.go:9:6"},
			want: "deadcode: x:New at x/a.go:9:6 is unreachable",
		},
		{
			name: "dead function renamed through lineage",
			base: tree{"a.go": "package p\n"}, pr: tree{"a.go": "package p\n"},
			baseDead: map[string]string{"x:Old": "x/a.go:1:6"}, prDead: map[string]string{"x:New": "x/a.go:9:6"},
			from: map[string]string{"x:New": "x:Old"},
			want: "deadcode: [x:New] cannot be split or renamed from x:Old",
		},
		{
			name: "an existing long function grows by one line",
			base: tree{"a.go": file(200, longFunc("Pass", 151))}, pr: tree{"a.go": file(200, longFunc("Pass", 152))},
			want: "long_functions: .:Pass grew to 152 lines, ceiling 151",
		},
		{
			name: "an existing complex function grows by one",
			base: baseTree, pr: baseTree.with(tree{"internal/r/mysql_runner.go": file(3592, complexFunc("Run", 61))}),
			want: "complex_functions: internal/r:Run grew to 61 complexity, ceiling 60",
		},
		{
			name: "a package-level func literal over 40", pr: tree{"a.go": "package p\n\nvar F = " + complexFunc("", 45)},
			want: "complex_functions: new function over 40 complexity: .:F",
		},
		{
			name: "split a long function, adding more than 2 lines per extra piece",
			base: tree{"a.go": file(700, longFunc("Pass", 320))}, pr: tree{"a.go": file(700, longFunc("PassA", 161)+longFunc("PassB", 162))},
			from: map[string]string{".:PassA": ".:Pass", ".:PassB": ".:Pass"},
			want: "long_functions: .:Pass split into [.:PassA .:PassB] has 323 lines in total",
		},
		{
			name: "switch an existing generated file to another generator",
			base: tree{"g.go": genHeader + file(900, "")}, baseGen: map[string]string{"g.go": "hand"},
			pr:       tree{"g.go": "// Code generated by other. DO NOT EDIT.\n" + file(900, "")},
			handEdit: func(b *Baseline) { b.Generated["g.go"] = "other" },
			want:     "generated_files: adds g.go, which existed before this change",
		},
		{name: "a new 5000-line test file", pr: tree{"a_test.go": file(5000, "")}, want: "test_files: new test file over 800 lines: a_test.go"},
		{
			name: "an existing complex test function grows",
			base: tree{"a_test.go": file(400, complexFunc("TestHot", 98))}, pr: tree{"a_test.go": file(400, complexFunc("TestHot", 99))},
			want: "test_complex_functions: .:TestHot grew to 99 complexity, ceiling 98",
		},
		{name: "a 900-line package under testdata", pr: tree{"x/testdata/big/b.go": file(900, "")}, want: "files: new file over 800 lines: x/testdata/big/b.go"},
		{name: "a 900-line package in a dot directory", pr: tree{"x/.hidden/b.go": file(900, "")}, want: "files: new file over 800 lines: x/.hidden/b.go"},
		{name: "loosen file_lines", base: baseTree, pr: baseTree, handEdit: func(b *Baseline) { b.Limits.FileLines++ }, want: "limits: file_lines loosened 800 -> 801"},
		{name: "loosen growth_tolerance_lines", base: baseTree, pr: baseTree, handEdit: func(b *Baseline) { b.Limits.GrowthTolerance++ }, want: "limits: growth_tolerance_lines loosened 20 -> 21"},
		{name: "loosen complexity", base: baseTree, pr: baseTree, handEdit: func(b *Baseline) { b.Limits.Complexity++ }, want: "limits: complexity loosened 40 -> 41"},
		{name: "loosen function_lines", base: baseTree, pr: baseTree, handEdit: func(b *Baseline) { b.Limits.FunctionLines++ }, want: "limits: function_lines loosened 150 -> 151"},
		{
			name: "raise a ceiling by hand", base: baseTree, pr: baseTree.with(tree{"internal/t/verifier.go": file(900, "")}),
			handEdit: func(b *Baseline) { b.Files["internal/t/verifier.go"] = Entry{Value: 900} },
			want:     "files: internal/t/verifier.go raised 837 -> 900",
		},
		{
			name: "add lineage to an existing entry", base: baseTree, pr: baseTree,
			handEdit: func(b *Baseline) {
				b.Files["internal/t/verifier.go"] = Entry{Value: 837, SplitFrom: "internal/r/mysql_runner.go"}
			},
			want: `files: internal/t/verifier.go changed split_from "" -> "internal/r/mysql_runner.go"`,
		},
		{
			name: "split that adds lines", base: baseTree,
			pr:   baseTree.with(tree{"internal/r/mysql_runner.go": "", "internal/r/a.go": file(1800, ""), "internal/r/b.go": file(1813, complexFunc("Run", 60))}),
			from: map[string]string{"internal/r/a.go": "internal/r/mysql_runner.go", "internal/r/b.go": "internal/r/mysql_runner.go"},
			want: "files: internal/r/mysql_runner.go split into [internal/r/a.go internal/r/b.go] has 3613 lines in total",
		},
		{
			name: "rename that grows", base: baseTree,
			pr:   baseTree.with(tree{"internal/t/verifier.go": "", "internal/t/verify.go": file(838, "")}),
			from: map[string]string{"internal/t/verify.go": "internal/t/verifier.go"},
			want: "has 838 lines in total (original left: 0), more than its ceiling 837 + 20 per extra piece",
		},
		{
			name: "FROM pair for something that is not a new entry", base: baseTree, pr: baseTree,
			from: map[string]string{"internal/t/small.go": "internal/t/verifier.go"},
			want: "FROM internal/t/small.go=internal/t/verifier.go: internal/t/small.go is not a new entry over a limit",
		},
		{
			name: "split mysql_runner.go in two halves", base: baseTree,
			pr:   baseTree.with(tree{"internal/r/mysql_runner.go": "", "internal/r/runner_a.go": file(1778, ""), "internal/r/runner_b.go": file(1833, complexFunc("Run", 60))}),
			from: map[string]string{"internal/r/runner_a.go": "internal/r/mysql_runner.go", "internal/r/runner_b.go": "internal/r/mysql_runner.go"},
		},
		{
			name: "split off a piece and keep the shrunken original", base: baseTree,
			pr:   baseTree.with(tree{"internal/r/mysql_runner.go": file(2500, complexFunc("Run", 60)), "internal/r/runner_b.go": file(1100, "")}),
			from: map[string]string{"internal/r/runner_b.go": "internal/r/mysql_runner.go"},
		},
		{
			name: "plain file rename", base: baseTree,
			pr:   baseTree.with(tree{"internal/t/verifier.go": "", "internal/t/verify.go": verifier}),
			from: map[string]string{"internal/t/verify.go": "internal/t/verifier.go"},
		},
		{
			name: "plain function rename", base: baseTree,
			pr:   baseTree.with(tree{"internal/r/mysql_runner.go": file(3592, complexFunc("Start", 60))}),
			from: map[string]string{"internal/r:Start": "internal/r:Run"},
		},
		{
			name: "split a complex function in two", base: baseTree,
			pr: baseTree.with(tree{"internal/r/mysql_runner.go": file(3592, complexFunc("RunA", 31)+complexFunc("RunB", 30))}),
		},
		{
			name: "rename a file with issue refs", base: tree{"a.go": "package p\n// #1 #2\n"}, pr: tree{"b.go": "package p\n// #1 #2\n"},
			from: map[string]string{"b.go": "a.go"},
		},
		{
			name: "a new generated file with its generator header", pr: tree{"x/g.go": genHeader + file(900, complexFunc("F", 50))},
			handEdit: func(b *Baseline) { b.Generated["x/g.go"] = "hand" },
		},
		{
			name: "split a long function, 2 lines per extra piece",
			base: tree{"a.go": file(700, longFunc("Pass", 320))}, pr: tree{"a.go": file(700, longFunc("PassA", 161)+longFunc("PassB", 161))},
			from: map[string]string{".:PassA": ".:Pass", ".:PassB": ".:Pass"},
		},
		{name: "pay down debt with make codehealth-baseline", base: baseTree, pr: baseTree.with(tree{"internal/t/verifier.go": file(700, "")})},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) { expect(t, c.run(t), c.want) })
	}
}
