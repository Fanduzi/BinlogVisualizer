package codehealth

import (
	"os/exec"
	"reflect"
	"testing"
)

const lintBase = `package p

func Run() {
	_ = 1
	_ = 2
	_ = 3
	_ = 4
	_ = 5
}

var top = 1
`

func issue(linter, file string, line int, text string) LintIssue {
	return LintIssue{Linter: linter, File: file, Line: line, Text: text}
}

// A finding matches its base finding when its function kept its key or
// moved with most of its body; line numbers and the function's own name in
// the message do not matter.
func TestDiffLint(t *testing.T) {
	base := measure(t, tree{"a.go": lintBase}, nil)
	baseIssues := []LintIssue{
		issue("errcheck", "a.go", 4, "Error return value of `Run` is not checked"),
		issue("gosec", "a.go", 11, "G101: top at line 11"),
		issue("gocyclo", "a.go", 3, "cyclomatic complexity 80 of func `Run` is high (> 40)"),
	}
	renamed := "package p\n\n// moved and renamed\n\nfunc RunMain() {\n\t_ = 1\n\t_ = 2\n\t_ = 3\n\t_ = 4\n\t_ = 5\n\t_ = 6\n}\n"
	cases := []struct {
		name   string
		pr     tree
		issues []LintIssue
		want   []string
	}{
		{"unchanged", tree{"a.go": lintBase}, baseIssues, nil},
		{"function renamed and moved to another file", tree{"b.go": renamed, "c.go": "package p\n\n\nvar top = 1\n"}, []LintIssue{
			issue("errcheck", "b.go", 7, "Error return value of `RunMain` is not checked"),
			issue("gosec", "c.go", 4, "G101: top at line 4"),
		}, nil},
		{"a second finding of the same kind", tree{"a.go": lintBase}, append(baseIssues, issue("errcheck", "a.go", 5, "Error return value of `Run` is not checked")), []string{"a.go:5: errcheck: Error return value of `Run` is not checked"}},
		{"another linter", tree{"a.go": lintBase}, append(baseIssues, issue("govet", "a.go", 4, "Error return value of `Run` is not checked")), []string{"a.go:4: govet:"}},
		{"same finding in a new function", tree{"a.go": lintBase + "\nfunc Other() {\n\t_ = 9\n}\n"}, append(baseIssues, issue("errcheck", "a.go", 14, "Error return value of `Other` is not checked")), []string{"a.go:14: errcheck"}},
		{"finding on the func line of a renamed function", tree{"b.go": renamed}, []LintIssue{issue("gocyclo", "b.go", 5, "cyclomatic complexity 80 of func `RunMain` is high (> 40)")}, nil},
		{"finding on the closing brace of a renamed function", tree{"b.go": renamed}, []LintIssue{issue("errcheck", "b.go", 12, "Error return value of `RunMain` is not checked")}, nil},
		{"moved body at exactly 80%", tree{"b.go": "package p\n\nfunc Other() {\n\t_ = 1\n\t_ = 2\n\t_ = 3\n\t_ = 4\n\t_ = 99\n}\n"}, []LintIssue{issue("errcheck", "b.go", 4, "Error return value of `Other` is not checked")}, nil},
		{"moved body at 60%", tree{"b.go": "package p\n\nfunc Other() {\n\t_ = 1\n\t_ = 2\n\t_ = 3\n\t_ = 98\n\t_ = 99\n}\n"}, []LintIssue{issue("errcheck", "b.go", 4, "Error return value of `Other` is not checked")}, []string{"b.go:4: errcheck"}},
		{"duplicates match in file then line order", tree{"a.go": lintBase, "b.go": "package p\n", "c.go": "package p\n"}, []LintIssue{
			issue("errcheck", "a.go", 4, "Error return value of `Run` is not checked"),
			issue("gosec", "c.go", 2, "G101: top at line 2"), issue("gosec", "b.go", 9, "G101: top at line 9"),
			issue("gosec", "a.go", 11, "G101: top at line 11"), issue("gosec", "a.go", 10, "G101: top at line 10"),
		}, []string{"a.go:11: gosec", "b.go:9: gosec", "c.go:2: gosec"}},
	}
	for _, c := range cases {
		pr := measure(t, c.pr, nil)
		got := DiffLint(base, baseIssues, pr, c.issues)
		if len(got) != len(c.want) {
			t.Errorf("%s: got %q, want %q", c.name, got, c.want)
			continue
		}
		for i := range got {
			expect(t, got[i:i+1], c.want[i])
		}
	}
}

// A function whose body is one line is still traced when renamed.
func TestDiffLintOneLineBody(t *testing.T) {
	base := measure(t, tree{"a.go": "package p\n\nfunc One() {\n\t_ = 7\n}\n"}, nil)
	pr := measure(t, tree{"a.go": "package p\n\nfunc Two() {\n\t_ = 7\n}\n"}, nil)
	got := DiffLint(base, []LintIssue{issue("errcheck", "a.go", 4, "x")}, pr, []LintIssue{issue("errcheck", "a.go", 4, "x")})
	if len(got) != 0 {
		t.Fatalf("got %q", got)
	}
}

func TestParseLint(t *testing.T) {
	got, err := ParseLint([]byte(`{"Issues":[{"FromLinter":"errcheck","Text":"x","Pos":{"Filename":"a/b.go","Line":3}}],"Report":{}}`))
	if err != nil || !reflect.DeepEqual(got, []LintIssue{issue("errcheck", "a/b.go", 3, "x")}) {
		t.Fatalf("parsed %v %v", got, err)
	}
	if _, err := ParseLint([]byte("level=error msg=typecheck")); err == nil {
		t.Fatal("text output accepted")
	}
}

// RunDeadcode reports dead functions in generated files too, except in the
// files listed as generated.
func TestRunDeadcode(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the pinned deadcode tool")
	}
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("no go command")
	}
	const gen = "// Code generated by hand. DO NOT EDIT.\n\npackage main\n\nfunc genDead() {}\n"
	root := tree{
		"go.mod":      "module m\n\ngo 1.22\n",
		"main.go":     "package main\n\nfunc main() { live() }\n\nfunc live() {}\n\nfunc dead() {}\n",
		"listed.go":   gen,
		"unlisted.go": "// Code generated by hand. DO NOT EDIT.\n\npackage main\n\nfunc genDead2() {}\n",
	}.write(t)
	if _, err := RunDeadcode(tree{"a.go": "package p\n"}.write(t), nil); err == nil {
		t.Fatal("deadcode outside a module succeeded")
	}
	dead, err := RunDeadcode(root, map[string]string{"listed.go": "hand"})
	if err != nil {
		t.Fatal(err)
	}
	if want := map[string]string{".:dead": "main.go:7:6", ".:genDead2": "unlisted.go:5:6"}; !reflect.DeepEqual(dead, want) {
		t.Fatalf("dead %v, want %v", dead, want)
	}
}
