package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const baselineRel = "internal/codehealth/baseline.json"

type fixture struct {
	t          *testing.T
	root       string
	dead       map[string]string
	deadCalled bool
	atBase     map[string]bool
}

func newFixture(t *testing.T, files map[string]string) *fixture {
	f := &fixture{t: t, root: t.TempDir(), atBase: map[string]bool{}}
	if err := os.MkdirAll(filepath.Join(f.root, filepath.Dir(baselineRel)), 0o755); err != nil {
		t.Fatal(err)
	}
	for name, src := range files {
		f.write(name, src)
	}
	return f
}

func (f *fixture) write(name, src string) {
	path := filepath.Join(f.root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		f.t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
		f.t.Fatal(err)
	}
}

func (f *fixture) read(name string) string {
	data, err := os.ReadFile(filepath.Join(f.root, filepath.FromSlash(name)))
	if err != nil {
		f.t.Fatal(err)
	}
	return string(data)
}

// run runs codehealth with -root set to the fixture and returns the exit
// code, stdout and stderr.
func (f *fixture) run(args ...string) (int, string, string) {
	var stdout, stderr bytes.Buffer
	d := deps{
		deadcode: func(root string) (map[string]string, error) {
			f.deadCalled = true
			return f.dead, nil
		},
		existedAtBase: func(root, rev, path string) bool { return rev == "BASE" && f.atBase[path] },
	}
	code := run(append([]string{"-root", f.root}, args...), &stdout, &stderr, d)
	return code, stdout.String(), stderr.String()
}

func (f *fixture) mustRun(args ...string) string {
	f.t.Helper()
	code, out, errOut := f.run(args...)
	if code != 0 {
		f.t.Fatalf("codehealth %v: exit %d\n%s", args, code, errOut)
	}
	return out
}

func (f *fixture) mustFail(want string, args ...string) {
	f.t.Helper()
	code, _, errOut := f.run(args...)
	if code != 1 || !strings.Contains(errOut, want) {
		f.t.Fatalf("codehealth %v: exit %d, want 1 with %q:\n%s", args, code, want, errOut)
	}
}

func lines(n int) string { return "package p\n" + strings.Repeat("\n", n-1) }

func TestInitThenCheck(t *testing.T) {
	f := newFixture(t, map[string]string{"a.go": lines(900), "g.go": "// Code generated by gen. DO NOT EDIT.\n" + lines(900)})
	f.dead = map[string]string{".:old": "a.go:3:6"}
	f.mustRun("-deadcode", "-generated", "g.go=gen", "init")
	b := f.read(baselineRel)
	for _, want := range []string{`"a.go": 900`, `"g.go": "gen"`, `".:old": 1`} {
		if !strings.Contains(b, want) {
			t.Fatalf("baseline lacks %s:\n%s", want, b)
		}
	}
	f.mustFail("already exists", "init")
	if out := f.mustRun("-deadcode", "check"); !strings.Contains(out, "ok: matches the baseline") {
		t.Fatalf("check output %q", out)
	}
	f.write("new.go", lines(801))
	f.mustFail("files: new file over 800 lines: new.go has 801", "check")
}

func TestCheckFindsDeadcodeOnlyWithTheFlag(t *testing.T) {
	f := newFixture(t, map[string]string{"a.go": lines(10)})
	f.mustRun("-deadcode", "init")
	f.dead = map[string]string{"x:New": "x/a.go:9:6"}
	f.deadCalled = false
	f.mustRun("check")
	if f.deadCalled {
		t.Fatal("check without -deadcode ran deadcode")
	}
	f.mustFail("deadcode: x:New at x/a.go:9:6 is unreachable", "-deadcode", "check")
	if out := f.mustRun("deadcode"); out != "x/a.go:9:6: x:New\n" {
		t.Fatalf("deadcode list %q", out)
	}
}

func TestUpdateRefusesToRaise(t *testing.T) {
	f := newFixture(t, map[string]string{"a.go": lines(900)})
	f.mustRun("init")
	before := f.read(baselineRel)
	f.write("a.go", lines(921))
	f.mustFail("refusing to raise the baseline", "update")
	f.write("b.go", lines(801))
	f.mustFail("refusing to raise the baseline", "update")
	if after := f.read(baselineRel); after != before {
		t.Fatalf("a refused update changed the baseline:\n%s", after)
	}
}

func TestUpdateLowersAndRecordsSplits(t *testing.T) {
	f := newFixture(t, map[string]string{"a.go": lines(1700)})
	f.mustRun("init")
	f.write("a.go", lines(850))
	f.mustFail("a.go is down to 850 lines, ceiling 1700; run make codehealth-baseline", "check")
	f.write("b.go", lines(850))
	f.mustFail("If it was split or renamed from a baseline entry: make codehealth-baseline FROM=b.go=OLD", "update")
	f.mustRun("-from", "b.go=a.go", "update")
	if b := f.read(baselineRel); !strings.Contains(b, `"a.go": 850`) || !strings.Contains(b, `"b.go": {`) || !strings.Contains(b, `"split_from": "a.go"`) {
		t.Fatalf("baseline after split:\n%s", b)
	}
	f.mustRun("check")
	if code, _, errOut := f.run("-from", "b.go", "update"); code != 2 || !strings.Contains(errOut, "want NEW=OLD") {
		t.Fatalf("bad -from: exit %d\n%s", code, errOut)
	}
}

func TestCompare(t *testing.T) {
	f := newFixture(t, map[string]string{"a.go": lines(900)})
	f.mustRun("init")
	prev := filepath.Join(f.root, "prev.json")
	if err := os.WriteFile(prev, []byte(f.read(baselineRel)), 0o644); err != nil {
		t.Fatal(err)
	}
	f.mustFail("usage: codehealth -base REV compare PREV.json", "compare", prev)
	if out := f.mustRun("-base", "BASE", "compare", prev); !strings.Contains(out, "ok: baseline only went down") {
		t.Fatalf("compare output %q", out)
	}
	f.write(baselineRel, strings.Replace(f.read(baselineRel), `"a.go": 900`, `"a.go": 901`, 1))
	f.mustFail("files: a.go raised 900 -> 901", "-base", "BASE", "compare", prev)
	f.write("g.go", "// Code generated by gen. DO NOT EDIT.\n"+lines(10))
	f.write(baselineRel, strings.Replace(f.read("prev.json"), `"generated_files": {}`, `"generated_files": {"g.go": "gen"}`, 1))
	f.mustRun("-base", "BASE", "compare", prev)
	f.atBase["g.go"] = true
	f.mustFail("generated_files: adds g.go, which existed before this change", "-base", "BASE", "compare", prev)
}

func TestRefsListsEveryReference(t *testing.T) {
	f := newFixture(t, map[string]string{"a.go": "package p\n\n// see #12 and GH-3\n"})
	f.mustRun("init")
	if out := f.mustRun("refs"); out != "a.go:3: #12\na.go:3: GH-3\n" {
		t.Fatalf("refs %q", out)
	}
}

func TestUsage(t *testing.T) {
	f := newFixture(t, nil)
	if code, _, _ := f.run(); code != 2 {
		t.Fatalf("no command: exit %d, want 2", code)
	}
	if code, _, _ := f.run("-nope"); code != 2 {
		t.Fatalf("bad flag: exit %d, want 2", code)
	}
	f.mustFail("unknown command", "frobnicate")
	f.mustFail("no such file", "check")
}
