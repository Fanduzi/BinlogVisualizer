// Package codehealth measures the code-health debt that CI ratchets and
// compares it with the checked-in baseline.json: oversized files, complex
// and long functions, issue references in comments and unreachable
// functions. Every baseline entry is a ceiling for one file or function. It
// may only go down or disappear, a new entry over a limit fails, and the
// only way to add one is as the recorded successor of an existing entry
// (a split or rename). docs/development/coding-standards.md has the rules.
package codehealth

import (
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// Limits are the caps the ratchet enforces. They live in the baseline so a
// change that loosens one shows up in review and fails Compare.
type Limits struct {
	FileLines       int `json:"file_lines"`
	GrowthTolerance int `json:"growth_tolerance_lines"`
	Complexity      int `json:"complexity"`
	FunctionLines   int `json:"function_lines"`
}

// DefaultLimits are the caps in docs/development/coding-standards.md.
var DefaultLimits = Limits{FileLines: 800, GrowthTolerance: 20, Complexity: 40, FunctionLines: 150}

// Func is one measured function: its cyclomatic complexity and its body
// length in lines.
type Func struct {
	Complexity int
	Lines      int
}

// Measurement holds every value Measure saw, over a limit or not, so that a
// split can be checked against the current size of its shrunken original.
type Measurement struct {
	// Files and TestFiles map a slash path to its line count.
	Files     map[string]int
	TestFiles map[string]int
	// Funcs and TestFuncs are keyed "pkgdir:Func", "pkgdir:Recv.Func", or
	// "pkgdir:name" for a function literal assigned to a package-level var.
	Funcs     map[string]Func
	TestFuncs map[string]Func
	// Refs maps a path to "line: text" for each issue reference in a comment.
	Refs map[string][]string
	// Generated maps each allowlisted path that exists to its first line.
	Generated map[string]string
	// Deadcode maps "pkgdir:Func" to its position; nil when not measured.
	Deadcode map[string]string
}

// goGenerated is the header Go recognizes as generated code
// (https://go.dev/s/generatedcode). Only the first line counts here.
var goGenerated = regexp.MustCompile(`^// Code generated .* DO NOT EDIT\.$`)

// GeneratedBy reports whether line is the Go generated-code header naming
// generator, for example "// Code generated by sqlc. DO NOT EDIT.".
func GeneratedBy(line, generator string) bool {
	rest, ok := strings.CutPrefix(line, "// Code generated by "+generator)
	return ok && goGenerated.MatchString(line) && (strings.HasPrefix(rest, ".") || strings.HasPrefix(rest, " "))
}

// Measure walks root and measures every Go file Go could compile: testdata,
// vendor, underscore and dot directories included. It skips .git,
// node_modules and nested modules (directories with their own go.mod). A
// file is skipped as generated only when generated (path -> generator)
// lists it and its first line is that generator's header.
func Measure(root string, generated map[string]string) (Measurement, error) {
	m := Measurement{
		Files: map[string]int{}, TestFiles: map[string]int{},
		Funcs: map[string]Func{}, TestFuncs: map[string]Func{},
		Refs: map[string][]string{}, Generated: map[string]string{},
	}
	fset := token.NewFileSet()
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return enterDir(root, path, d.Name())
		}
		if !strings.HasSuffix(path, ".go") {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		return m.addFile(fset, path, filepath.ToSlash(rel), generated)
	})
	return m, err
}

func enterDir(root, path, name string) error {
	if path == root {
		return nil
	}
	if name == ".git" || name == "node_modules" {
		return filepath.SkipDir
	}
	if _, err := os.Stat(filepath.Join(path, "go.mod")); err == nil {
		return filepath.SkipDir
	}
	return nil
}

func (m *Measurement) addFile(fset *token.FileSet, path, rel string, generated map[string]string) error {
	src, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if gen, ok := generated[rel]; ok {
		first, _, _ := strings.Cut(string(src), "\n")
		m.Generated[rel] = strings.TrimSuffix(first, "\r")
		if GeneratedBy(m.Generated[rel], gen) {
			return nil
		}
	}
	f, err := parser.ParseFile(fset, path, src, parser.ParseComments)
	if err != nil {
		return err
	}
	if refs := issueRefs(fset, f); len(refs) > 0 {
		m.Refs[rel] = refs
	}
	files, funcs := m.Files, m.Funcs
	if strings.HasSuffix(rel, "_test.go") {
		files, funcs = m.TestFiles, m.TestFuncs
	}
	files[rel] = countLines(src)
	pkg := filepath.ToSlash(filepath.Dir(rel))
	for name, fn := range functions(fset, f, strings.Split(string(src), "\n")) {
		key := pkg + ":" + name
		old := funcs[key]
		funcs[key] = Func{Complexity: max(old.Complexity, fn.Complexity), Lines: max(old.Lines, fn.Lines)}
	}
	return nil
}

func countLines(src []byte) int {
	n := strings.Count(string(src), "\n")
	if len(src) > 0 && src[len(src)-1] != '\n' {
		n++
	}
	return n
}

// functions measures each function declared in f and each function literal
// assigned to a package-level var. Function literals inside a function count
// toward that function, as in gocyclo; a literal nested in a package-level
// literal is measured too, but its enclosing literal always counts more.
func functions(fset *token.FileSet, f *ast.File, lines []string) map[string]Func {
	out := map[string]Func{}
	add := func(name string, body *ast.BlockStmt) {
		fn := Func{Complexity: complexity(body), Lines: bodyLines(fset, body, lines)}
		old := out[name]
		out[name] = Func{Complexity: max(old.Complexity, fn.Complexity), Lines: max(old.Lines, fn.Lines)}
	}
	for _, decl := range f.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if d.Body != nil {
				add(funcName(d), d.Body)
			}
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				if vs, ok := spec.(*ast.ValueSpec); ok {
					for i, v := range vs.Values {
						forEachLiteral(v, func(lit *ast.FuncLit) { add(specName(vs, i), lit.Body) })
					}
				}
			}
		}
	}
	return out
}

func forEachLiteral(n ast.Node, fn func(*ast.FuncLit)) {
	ast.Inspect(n, func(n ast.Node) bool {
		if lit, ok := n.(*ast.FuncLit); ok {
			fn(lit)
		}
		return true
	})
}

func specName(vs *ast.ValueSpec, i int) string {
	if i < len(vs.Names) {
		return vs.Names[i].Name
	}
	return vs.Names[0].Name
}

// bodyLines counts the lines between the braces, not counting lines that
// hold only a // comment, like funlen with ignore-comments.
func bodyLines(fset *token.FileSet, body *ast.BlockStmt, lines []string) int {
	first, last := fset.Position(body.Lbrace).Line, fset.Position(body.Rbrace).Line
	n := 0
	for i := first; i < last-1; i++ {
		if !strings.HasPrefix(strings.TrimSpace(lines[i]), "//") {
			n++
		}
	}
	return n
}
