// A server-generated DROP TABLE that names tables in two schemas must show
// each schema.table in the report. The old text split turned
// `x`,`q368_b`.`t1` into one table and dropped q368_a.
func TestAnalyzeCrossSchemaDropReportsEachTable(t *testing.T) {
	base := time.Date(2026, 10, 20, 9, 17, 23, 0, time.UTC)
	sql := "DROP TABLE `x`,`q368_b`.`t1` /* generated by server */"
	result, err := New(DefaultOptions()).Analyze([]model.NormalizedEvent{{
		Timestamp:   base,
		EventType:   "DDL",
		Schema:      "q368_a",
		BinlogBytes: 120,
		QuerySQL:    sql,
	}})
	if err != nil {
		t.Fatalf("Analyze: %v", err)
	}
	want := map[string]bool{"q368_a.x": false, "q368_b.t1": false}
	for _, event := range result.Diagnostics.DDLEvents {
		if event.Operation != "DROP TABLE" {
			continue
		}
		name := event.Schema + "." + event.Table
		if _, ok := want[name]; !ok {
			t.Fatalf("DDL target %s, events %+v", name, result.Diagnostics.DDLEvents)
		}
		want[name] = true
		if strings.Contains(event.Schema, "`") || strings.Contains(event.Table, "`") {
			t.Fatalf("DDL target still split as text: %+v", event)
		}
	}
	for name, seen := range want {
		if !seen {
			t.Fatalf("missing DDL target %s in %+v", name, result.Diagnostics.DDLEvents)
		}
	}
	for _, table := range result.Tables {
		name := table.Schema + "." + table.Table
		if name != "q368_a.x" && name != "q368_b.t1" {
			t.Fatalf("table %s bytes=%d, want only the two dropped tables", name, table.BinlogBytes)
		}
		if table.BinlogBytes <= 0 || table.DDLCount != 1 {
			t.Fatalf("table %s bytes=%d ddl=%d, want the statement charged to each table", name, table.BinlogBytes, table.DDLCount)
		}
	}
	if len(result.Tables) != 2 {
		t.Fatalf("tables = %+v, want 2", result.Tables)
	}

	opts := report.DefaultOptions()
	jsonOut, err := report.RenderJSONWithOptions(*result, opts)
	if err != nil {
		t.Fatalf("json: %v", err)
	}
	var doc struct {
		Tables []struct {
			Schema string `json:"schema"`
			Table  string `json:"table"`
		} `json:"tables"`
		Diagnostics struct {
			DDLEvents []struct {
				Schema    string `json:"schema"`
				Table     string `json:"table"`
				Operation string `json:"operation"`
			} `json:"ddl_events"`
		} `json:"diagnostics"`
	}
	if err := json.Unmarshal([]byte(jsonOut), &doc); err != nil {
		t.Fatalf("decode: %v\n%s", err, jsonOut)
	}
	gotDDL := map[string]int{}
	for _, event := range doc.Diagnostics.DDLEvents {
		if strings.Contains(event.Schema, "`") || strings.Contains(event.Table, ",") {
			t.Fatalf("json ddl target %s.%s", event.Schema, event.Table)
		}
		gotDDL[event.Schema+"."+event.Table]++
	}
	if gotDDL["q368_a.x"] != 1 || gotDDL["q368_b.t1"] != 1 {
		t.Fatalf("json ddl = %v", gotDDL)
	}
	gotTables := map[string]bool{}
	for _, table := range doc.Tables {
		gotTables[table.Schema+"."+table.Table] = true
	}
	if !gotTables["q368_a.x"] || !gotTables["q368_b.t1"] {
		t.Fatalf("json tables = %v", gotTables)
	}

	text, err := report.RenderTextWithOptions(*result, opts)
	if err != nil {
		t.Fatalf("text: %v", err)
	}
	md, err := report.RenderMarkdownWithOptions(*result, opts)
	if err != nil {
		t.Fatalf("markdown: %v", err)
	}
	html, err := report.RenderHTMLWithOptions(*result, opts)
	if err != nil {
		t.Fatalf("html: %v", err)
	}
	for _, out := range []string{text, md, html} {
		if !strings.Contains(out, "q368_a.x") || !strings.Contains(out, "q368_b.t1") {
			t.Fatalf("report missing a dropped table:\n%s", out)
		}
	}
	if !strings.Contains(text, "Top table bytes:") || !strings.Contains(text, "q368_a.x") || !strings.Contains(text, "q368_b.t1") {
		t.Fatalf("top table bytes:\n%s", text)
	}
}

// A multi-pair RENAME TABLE must show each pair's old table, the same way a
// multi-table DROP TABLE shows each target: only the first pair used to be
// attributed, so the rest of the statement was invisible.
func TestAnalyzeMultiPairRenameReportsEachOldTable(t *testing.T) {
	base := time.Date(2026, 10, 20, 9, 17, 23, 0, time.UTC)
	sql := "RENAME TABLE `a` TO `b`, `s2`.`c` TO `s2`.`d`"
	result, err := New(DefaultOptions()).Analyze([]model.NormalizedEvent{{
		Timestamp:   base,
		EventType:   "DDL",
		Schema:      "s1",
		BinlogBytes: 120,
		QuerySQL:    sql,
	}})
	if err != nil {
		t.Fatalf("Analyze: %v", err)
	}
	want := map[string]bool{"s1.a": false, "s2.c": false}
	for _, event := range result.Diagnostics.DDLEvents {
		if event.Operation != "RENAME TABLE" {
			continue
		}
		name := event.Schema + "." + event.Table
		if _, ok := want[name]; !ok {
			t.Fatalf("DDL target %s, events %+v", name, result.Diagnostics.DDLEvents)
		}
		want[name] = true
	}
	for name, seen := range want {
		if !seen {
			t.Fatalf("missing DDL target %s in %+v", name, result.Diagnostics.DDLEvents)
		}
	}
}
