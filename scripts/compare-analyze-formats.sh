#!/usr/bin/env bash
# Compare analyze and flashback output of two binlogviz binaries.
# Usage: scripts/compare-analyze-formats.sh <old-binary> <new-binary> [repo-root]
# HTML generated-at timestamps are normalized before the diff. Every other byte is compared.
set -euo pipefail

if [[ $# -lt 2 ]]; then
	echo "usage: $0 <old-binary> <new-binary> [repo-root]" >&2
	exit 2
fi

old=$1
new=$2
root=${3:-.}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

normalize_html() {
	sed -E \
		-e 's#(Generated</strong>[[:space:]]*)[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}:[0-9]{2} UTC#\1TIME#g' \
		-e 's#(Generated by BinlogViz &middot; )[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}:[0-9]{2} UTC#\1TIME#g' \
		-e 's#(- Generated: )[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}:[0-9]{2} UTC#\1TIME#g' \
		"$1"
}

run_one() {
	local bin=$1
	local stdout=$2
	local stderr=$3
	shift 3
	set +e
	"$bin" --quiet --lang en "$@" >"$stdout" 2>"$stderr"
	local code=$?
	set -e
	printf '%s' "$code"
}

mapfile -d '' binlogs < <(find "$root" -name '*.binlog' -type f -print0 | sort -z)

identical=0
differ=0
binlog_count=${#binlogs[@]}
declare -a diffs

compare_pair() {
	local label=$1
	local kind=$2
	shift 2
	local a_out=$work/a.out b_out=$work/b.out a_err=$work/a.err b_err=$work/b.err
	local a_code b_code
	a_code=$(run_one "$old" "$a_out" "$a_err" "$@")
	b_code=$(run_one "$new" "$b_out" "$b_err" "$@")
	if [[ $kind == html ]]; then
		normalize_html "$a_out" >"$work/a.norm"
		normalize_html "$b_out" >"$work/b.norm"
		mv "$work/a.norm" "$a_out"
		mv "$work/b.norm" "$b_out"
	fi
	local same=1
	if [[ $a_code != "$b_code" ]]; then
		same=0
	fi
	if ! cmp -s "$a_out" "$b_out"; then
		same=0
	fi
	if ! cmp -s "$a_err" "$b_err"; then
		same=0
	fi
	if [[ $same -eq 1 ]]; then
		identical=$((identical + 1))
		return
	fi
	differ=$((differ + 1))
	diffs+=("$label exit $a_code/$b_code")
	diff -u "$a_out" "$b_out" | head -n 40 >&2 || true
	diff -u "$a_err" "$b_err" | head -n 20 >&2 || true
}

for binlog in "${binlogs[@]}"; do
	rel=${binlog#"$root"/}
	for format in text json markdown html; do
		args=(analyze "$binlog" --format "$format")
		if [[ $format == html ]]; then
			args+=(--output -)
		fi
		compare_pair "$rel analyze $format" "$format" "${args[@]}"
	done
	compare_pair "$rel flashback sql" sql flashback "$binlog"
	compare_pair "$rel flashback plan" plan flashback "$binlog" --plan
done

echo "binlogs=$binlog_count comparisons=$((identical + differ)) identical=$identical differ=$differ"
echo "formats=text,json,markdown,html,flashback-sql,flashback-plan"
echo "html=generated-at timestamps normalized"
if [[ $differ -ne 0 ]]; then
	printf 'diff: %s\n' "${diffs[@]}"
	exit 1
fi
